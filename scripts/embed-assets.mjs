// Embeds public/ into src/static.generated.ts so the Worker can serve its pages without the
// separate assets upload (used when deploying through the Cloudflare API rather than wrangler).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const types = { html: "text/html; charset=utf-8", css: "text/css; charset=utf-8", js: "text/javascript; charset=utf-8" };
const files = {};
for (const f of readdirSync("public")) {
  const ext = f.split(".").pop();
  if (!types[ext]) continue;
  files["/" + f] = { type: types[ext], body: readFileSync("public/" + f, "utf8") };
}
// Version-tag stylesheet and script links so browsers (and pages embedding us) always fetch the
// current file after a deploy instead of a cached copy.
for (const [path, f] of Object.entries(files)) {
  if (!path.endsWith(".html")) continue;
  for (const [asset, a] of Object.entries(files)) {
    if (asset.endsWith(".html")) continue;
    const v = createHash("sha256").update(a.body).digest("hex").slice(0, 10);
    f.body = f.body.split(`"${asset}"`).join(`"${asset}?v=${v}"`);
  }
}
writeFileSync("src/static.generated.ts", "// Generated by scripts/embed-assets.mjs. Do not edit.\nexport const STATIC: Record<string, { type: string; body: string }> = " + JSON.stringify(files) + ";\n");
console.log("embedded", Object.keys(files));
